-- Example: tracking data citations FROM and TO a funder's papers (here: NIH, GRID grid.94365.3d,
-- including all child institutes via the organization hierarchy), broken down by what KIND of
-- thing was cited.
--
-- Demonstrates the two flagship joins on the data_citations view:
--   FROM: what a funder's papers generate (Primary) and reuse (Secondary)
--   TO:   Primary pairs define the funder's GENERATED datasets; Secondary citations of those
--         datasets by other papers measure reuse — split by whether the reusing paper is
--         itself funder-supported (internal) or not (external spillover).
--
-- Every row carries two labels describing the cited thing:
--   data_class  the DataCite resourceTypeGeneral of a DOI (Dataset, Software, Collection, Text, ...),
--               or 'Accession' for a repository accession number (GenBank, PDB, GEO, ...). A DOI with
--               no DataCite record is 'Unknown DOI type'.
--   scope       'data type'              resourceTypeGeneral is in the data-ish set (is_data_type = TRUE):
--                                         Dataset, Software, Collection, Image, Model, ... and every accession.
--               'other DataCite record'  anything else (Text, JournalArticle, Report, Service, Award, ...).
--                                         These are real citations to DataCite DOIs, but not datasets in any
--                                         ordinary sense, so read them as their own analysis. At NIH, "Primary"
--                                         here is mostly authors' own deposits (code, supplements, OSF projects,
--                                         pre-registrations) in general-purpose repositories where the depositor
--                                         chose a generic type label; "Secondary" is mostly citation of
--                                         papers, scales and methods in institutional repositories.
--
-- Filter `scope = 'data type'` to reproduce a conventional data-citation analysis; filter
-- `scope = 'other DataCite record'` for the separate non-dataset analysis.
--
-- Requires in tables.yaml: work_dataset, publications_metadata (with funder_orgs + id/year),
-- organizations_metadata (with organization_recursive_child_ids).
-- Swap the GRID id to profile any funder; add family_or_repo / year grouping for trends.

WITH nih_pubs AS (   -- NIH (grid.94365.3d) incl. all child institutes
  SELECT DISTINCT p.id, p.year
  FROM `${publications_metadata}` p,
       UNNEST(funder_orgs) fo
  INNER JOIN `${organizations_metadata}` o
    ON o.id = 'grid.94365.3d'
   AND (fo = o.id OR fo IN UNNEST(o.organization_recursive_child_ids))
),
-- The product view with the two labels above attached
cites AS (
  SELECT v.publication_id, v.dataset_id, v.id_kind, v.type,
         IF(v.is_data_type, 'data type', 'other DataCite record') AS scope,
         CASE WHEN v.id_kind = 'accession'    THEN 'Accession'
              WHEN v.resource_type IS NULL    THEN 'Unknown DOI type'
              ELSE v.resource_type END         AS data_class
  FROM `${work_dataset}.data_citations` v
  WHERE v.type IN ('Primary','Secondary')
),
-- Direction 1: FROM — citations made by NIH-funded papers
from_nih AS (
  SELECT c.scope, c.data_class, c.type, COUNT(*) n, COUNT(DISTINCT c.publication_id) papers
  FROM cites c
  JOIN nih_pubs ON nih_pubs.id = c.publication_id
  GROUP BY 1, 2, 3
),
-- Direction 2: TO — records GENERATED by NIH-funded papers...
nih_generated AS (
  SELECT DISTINCT c.dataset_id, c.id_kind, c.scope, c.data_class, c.publication_id AS generating_pub
  FROM cites c
  JOIN nih_pubs ON nih_pubs.id = c.publication_id
  WHERE c.type = 'Primary'
),
-- ...and every reuse of those records by OTHER papers
reuse_of_nih_data AS (
  SELECT g.scope, g.data_class,
         COUNT(*) reuse_citations,
         COUNT(DISTINCT c.dataset_id) datasets_reused,
         COUNT(DISTINCT c.publication_id) reusing_papers,
         COUNTIF(nih2.id IS NOT NULL) reuse_by_nih_funded,
         COUNTIF(nih2.id IS NULL) reuse_by_external
  FROM cites c
  JOIN nih_generated g ON g.dataset_id = c.dataset_id AND g.id_kind = c.id_kind
  LEFT JOIN nih_pubs nih2 ON nih2.id = c.publication_id
  WHERE c.type = 'Secondary' AND c.publication_id != g.generating_pub
  GROUP BY 1, 2
)
SELECT 'FROM: NIH papers citing data' AS direction, scope, data_class,
       type AS slice,
       n AS citations, papers AS distinct_papers,
       NULL AS datasets_reused, NULL AS by_nih, NULL AS by_external
FROM from_nih
UNION ALL
SELECT 'TO: reuse of NIH-generated data', scope, data_class,
       'Secondary',
       reuse_citations, reusing_papers, datasets_reused, reuse_by_nih_funded, reuse_by_external
FROM reuse_of_nih_data
ORDER BY direction, scope DESC, citations DESC
