-- 5 (expose the model used).
--
-- `rules` and `methods` are hand-authored literals rather than derived, because the thing being
-- published is the DEFINITION of each rule and the provenance of each method, and neither exists
-- as data anywhere in the pipeline -- they exist as SQL and as measurements recorded in commit
-- messages and docs. Encoding them here is deliberate: it makes the definitions queryable, and
-- it makes them fail loudly when a rule changes and this table is not updated.
--
-- `measured_precision` is NULL wherever a rule has never been measured on the population it
-- actually decides. That is not laziness. Borrowing a precision figure from a different
-- population is the specific error that produced two wrong conclusions in this project (an
-- 84.5%-vs-1.1% "divergence" that was a selection artefact, and a residue base-rate estimate of
-- 10-14% where direct labelling measured 50%), so a NULL here is a stronger statement than a
-- number.

