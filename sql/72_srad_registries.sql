-- Accession parsers: the regex per family, with its false-positive risk. Requirement 2's parser
-- half. Derived from the pipeline's own lexicon so it cannot drift from what actually ran.
CREATE OR REPLACE TABLE `${srad_dataset}.accession_patterns` AS
SELECT
  family,
  pattern,
  fp_risk,
  default_type_prior,
  patterns_key,
  (fp_risk != 'low' OR pattern IS NULL) AS excluded_from_regex_discovery,
  CAST(NULL AS STRING) AS fp_notes
FROM `${work_dataset}.accession_families`;


-- Cue lexicon: the deposition/reuse phrases and their weights, exactly as scored.
CREATE OR REPLACE TABLE `${srad_dataset}.cue_lexicon` AS
SELECT cue_id, direction, pattern, weight
FROM `${work_dataset}.classification_cues`;


